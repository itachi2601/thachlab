-- Sổ học phí theo tháng cho khoá THPT. Không cổng thanh toán, không đổi
-- thpt_registrations.payment_status (ô "Đã đóng" hiện tại giữ nguyên).
--
-- Ẩn mặc định: staff_visible = false, family_visible = false.
-- Mọi hàm ghi từ chối khi staff_visible còn false, kể cả admin gọi RPC.
-- Cách duy nhất để giáo viên thấy sổ là SQL (không có nút, không có menu):
--   update public.thpt_fee_settings set staff_visible = true, updated_at = now() where id;
-- rồi mở /quan-tri/hoc-phi (đường dẫn không nằm trong menu quản trị).
-- Trong trang đó admin mới bật được family_visible — lúc đó phụ huynh thấy
-- từng tháng trên thẻ Học phí. Học sinh không bao giờ thấy sổ này.
--
-- Một học sinh + một mức thu + một tháng = một khoản. Lớp 2 buổi (pair) chỉ
-- một khoản, không thu đúp buổi A và buổi B. Khoá billing_key phải khớp
-- billingKeyOf trong features/tuition/ledger.ts (kiểm bằng scripts/test-tuition-ledger.mts).
--
-- Chạy bất kỳ lúc nào: chỉ thêm bảng và hàm. Rollback ở cuối file và
-- perf/rollback/20261006120000_thpt_fee_ledger.down.sql.
