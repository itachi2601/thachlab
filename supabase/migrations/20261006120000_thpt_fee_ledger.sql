-- BEGIN billing_key
create or replace function public.thpt_fee_billing_key(
  p_course_id bigint, p_name text, p_pair_key text, p_pair_slot text
) returns text
language sql immutable
as $$
  select case
    when slot is null or slot = '' then 'course:' || p_course_id::text
    else 'pair:' || coalesce(nullif(btrim(coalesce(p_pair_key, '')), ''), nullif(btrim(head), ''), btrim(coalesce(p_name, '')))
  end
  from (
    select
      upper(coalesce(
        nullif(btrim(coalesce(p_pair_slot, '')), ''),
        substring(coalesce(p_name, '') from '(?i)buổi[[:space:]]+([A-Za-z])')
      )) as slot,
      regexp_replace(coalesce(p_name, ''), '\s+[—–-]\s+.*$', '') as head
  ) s;
$$;
-- END billing_key

create or replace function public.thpt_fee_is_clerk()
returns boolean
language sql stable security definer set search_path = public
as $$
  select public.is_admin()
    or exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and p.role = 'instructor'
        and p.admin_area = 'thpt'
    );
$$;

create or replace function public.thpt_fee_assert_open(p_class bigint)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if (select auth.uid()) is null then raise exception 'Chưa đăng nhập.'; end if;
  if not public.thpt_fee_is_clerk() then raise exception 'Không có quyền.'; end if;
  if not exists (select 1 from public.thpt_fee_settings s where s.id and s.staff_visible) then
    raise exception 'Sổ học phí đang ẩn.';
  end if;
  if p_class is not null and not public.manages_class(p_class) then
    raise exception 'Không có quyền với lớp này.';
  end if;
end;
$$;

create or replace function public.thpt_fee_visibility()
returns table (staff_visible boolean, family_visible boolean)
language plpgsql stable security definer set search_path = public
as $$
begin
  if not public.thpt_fee_is_clerk() then
    staff_visible := false;
    family_visible := false;
    return next;
    return;
  end if;
  return query
    select s.staff_visible, s.family_visible
    from public.thpt_fee_settings s
    where s.id;
  if not found then
    staff_visible := false;
    family_visible := false;
    return next;
  end if;
end;
$$;

-- Không bật được staff_visible qua hàm này. Cờ đó chỉ đổi bằng SQL ở đầu file.
create or replace function public.thpt_fee_set_visibility(p_staff boolean, p_family boolean)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Không có quyền.'; end if;
  if not exists (select 1 from public.thpt_fee_settings s where s.id and s.staff_visible) then
    raise exception 'Sổ học phí đang ẩn.';
  end if;
  update public.thpt_fee_settings
     set staff_visible = p_staff, family_visible = p_family, updated_at = now()
   where id;
end;
$$;

create or replace function public.thpt_fee_plans(p_class bigint)
returns table (
  id bigint, class_id bigint, billing_key text, label text,
  amount_vnd integer, due_day smallint, active boolean
)
language plpgsql stable security definer set search_path = public
as $$
begin
  perform public.thpt_fee_assert_open(p_class);
  return query
    select p.id, p.class_id, p.billing_key, p.label, p.amount_vnd, p.due_day, p.active
    from public.thpt_fee_plans p
    where p.class_id = p_class
    order by p.label;
end;
$$;

create or replace function public.thpt_fee_upsert_plan(
  p_class bigint, p_billing_key text, p_label text, p_amount integer, p_due_day smallint
) returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  v_id bigint;
  v_label text := btrim(p_label);
begin
  perform public.thpt_fee_assert_open(p_class);
  if v_label is null or char_length(v_label) < 1 or char_length(v_label) > 80 then
    raise exception 'Tên mức thu không hợp lệ.';
  end if;
  if p_amount is null or p_amount < 1 or p_amount > 20000000 then
    raise exception 'Số tiền không hợp lệ.';
  end if;
  if p_due_day is null or p_due_day < 1 or p_due_day > 28 then
    raise exception 'Ngày hạn không hợp lệ.';
  end if;
  if not exists (
    select 1 from public.thpt_courses c
    where c.class_id = p_class
      and public.thpt_fee_billing_key(c.id, c.name, c.pair_key, c.pair_slot) = p_billing_key
  ) then
    raise exception 'Không khớp lớp nào.';
  end if;
  insert into public.thpt_fee_plans (class_id, billing_key, label, amount_vnd, due_day, active, created_by)
  values (p_class, p_billing_key, v_label, p_amount, p_due_day, true, auth.uid())
  on conflict (class_id, billing_key) do update
    set label = excluded.label, amount_vnd = excluded.amount_vnd, due_day = excluded.due_day, active = true
  returning thpt_fee_plans.id into v_id;
  return v_id;
end;
$$;

create or replace function public.thpt_fee_archive_plan(p_plan bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_class bigint;
begin
  select class_id into v_class from public.thpt_fee_plans where id = p_plan;
  if v_class is null then raise exception 'Không thấy mức thu.'; end if;
  perform public.thpt_fee_assert_open(v_class);
  update public.thpt_fee_plans set active = false where id = p_plan;
end;
$$;

create or replace function public.thpt_fee_ensure_month(p_class bigint, p_period date)
returns integer
language plpgsql security definer set search_path = public
as $$
declare
  v_period date := date_trunc('month', p_period)::date;
  v_n integer;
begin
  perform public.thpt_fee_assert_open(p_class);
  if v_period < date '2024-01-01'
     or v_period > (date_trunc('month', (now() at time zone 'Asia/Ho_Chi_Minh'))::date + interval '1 month') then
    raise exception 'Tháng không hợp lệ.';
  end if;
  with ins as (
    insert into public.thpt_fee_charges (plan_id, student_id, period, amount_vnd)
    select distinct on (p.id, r.student_id)
           p.id, r.student_id, v_period, p.amount_vnd
      from public.thpt_fee_plans p
      join public.thpt_courses c on c.class_id = p.class_id
      join public.thpt_registrations r on r.course_id = c.id
     where p.class_id = p_class
       and p.active
       and p.billing_key = public.thpt_fee_billing_key(c.id, c.name, c.pair_key, c.pair_slot)
       and r.student_id is not null
       and r.status in ('active', 'catchup')
     order by p.id, r.student_id, r.id
    on conflict (plan_id, student_id, period) do nothing
    returning 1
  )
  select count(*)::int into v_n from ins;
  return v_n;
end;
$$;

create or replace function public.thpt_fee_ledger(p_class bigint, p_period date)
returns table (
  charge_id bigint, plan_id bigint, student_id uuid, student_name text,
  billing_key text, label text, period date, amount_vnd integer,
  paid_vnd integer, waived boolean, due_day smallint
)
language plpgsql stable security definer set search_path = public
as $$
declare
  v_period date := date_trunc('month', p_period)::date;
begin
  perform public.thpt_fee_assert_open(p_class);
  return query
    select c.id, c.plan_id, c.student_id, coalesce(pr.full_name, 'Học sinh'),
           p.billing_key, p.label, c.period, c.amount_vnd,
           coalesce(sum(pay.amount_vnd), 0)::int, c.waived, p.due_day
      from public.thpt_fee_charges c
      join public.thpt_fee_plans p on p.id = c.plan_id
      join public.profiles pr on pr.id = c.student_id
      left join public.thpt_fee_payments pay on pay.charge_id = c.id
     where p.class_id = p_class and c.period = v_period
     group by c.id, p.billing_key, p.label, p.due_day, pr.full_name
     order by pr.full_name, p.label;
end;
$$;

create or replace function public.thpt_fee_record_payment(
  p_charge bigint, p_amount integer, p_method text, p_paid_on date, p_note text
) returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_class bigint;
  v_note text := btrim(coalesce(p_note, ''));
begin
  select p.class_id into v_class
    from public.thpt_fee_charges c
    join public.thpt_fee_plans p on p.id = c.plan_id
   where c.id = p_charge;
  if v_class is null then raise exception 'Không thấy khoản thu.'; end if;
  perform public.thpt_fee_assert_open(v_class);
  if p_amount is null or p_amount < 1 or p_amount > 20000000 then
    raise exception 'Số tiền không hợp lệ.';
  end if;
  if p_method not in ('center', 'transfer') then
    raise exception 'Hình thức không hợp lệ.';
  end if;
  if p_paid_on < date '2024-01-01'
     or p_paid_on > (now() at time zone 'Asia/Ho_Chi_Minh')::date + 1 then
    raise exception 'Ngày không hợp lệ.';
  end if;
  if char_length(v_note) > 300 then raise exception 'Ghi chú quá dài.'; end if;
  insert into public.thpt_fee_payments (charge_id, amount_vnd, method, paid_on, note, recorded_by)
  values (p_charge, p_amount, p_method, p_paid_on, v_note, auth.uid());
end;
$$;

create or replace function public.thpt_fee_waive(p_charge bigint, p_waived boolean)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_class bigint;
begin
  select p.class_id into v_class
    from public.thpt_fee_charges c
    join public.thpt_fee_plans p on p.id = c.plan_id
   where c.id = p_charge;
  if v_class is null then raise exception 'Không thấy khoản thu.'; end if;
  perform public.thpt_fee_assert_open(v_class);
  update public.thpt_fee_charges set waived = p_waived where id = p_charge;
end;
$$;

-- Phụ huynh đọc khoản của con. family_visible = false → bảng rỗng, không báo lỗi,
-- để thẻ Học phí trên /phu-huynh giữ nguyên như khi chưa có sổ.
create or replace function public.thpt_fee_family_lines()
returns table (
  student_id uuid, student_name text, billing_key text, label text,
  period date, amount_vnd integer, paid_vnd integer, waived boolean, due_day smallint
)
language plpgsql stable security definer set search_path = public
as $$
begin
  if (select auth.uid()) is null then return; end if;
  if not exists (select 1 from public.thpt_fee_settings s where s.id and s.family_visible) then
    return;
  end if;
  return query
    select c.student_id, coalesce(pr.full_name, ''), p.billing_key, p.label,
           c.period, c.amount_vnd, coalesce(sum(pay.amount_vnd), 0)::int, c.waived, p.due_day
      from public.thpt_fee_charges c
      join public.thpt_fee_plans p on p.id = c.plan_id
      join public.profiles pr on pr.id = c.student_id
      left join public.thpt_fee_payments pay on pay.charge_id = c.id
     where public.is_parent_of(c.student_id)
       and c.period >= (date_trunc('month', (now() at time zone 'Asia/Ho_Chi_Minh'))::date - interval '5 months')
       and c.period <= date_trunc('month', (now() at time zone 'Asia/Ho_Chi_Minh'))::date
     group by c.id, c.student_id, pr.full_name, p.billing_key, p.label, p.due_day
     order by c.period desc, p.label;
end;
$$;

