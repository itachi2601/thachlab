create table if not exists public.thpt_fee_settings (
  id boolean primary key default true check (id),
  staff_visible boolean not null default false,
  family_visible boolean not null default false,
  updated_at timestamptz not null default now()
);
insert into public.thpt_fee_settings (id, staff_visible, family_visible)
values (true, false, false)
on conflict (id) do nothing;

create table if not exists public.thpt_fee_plans (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes (id) on delete cascade,
  billing_key text not null check (char_length(billing_key) between 1 and 120),
  label text not null check (char_length(label) between 1 and 80),
  amount_vnd integer not null check (amount_vnd between 1 and 20000000),
  due_day smallint not null default 5 check (due_day between 1 and 28),
  active boolean not null default true,
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  unique (class_id, billing_key)
);

create table if not exists public.thpt_fee_charges (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.thpt_fee_plans (id) on delete cascade,
  student_id uuid not null references public.profiles (id) on delete cascade,
  period date not null,
  amount_vnd integer not null check (amount_vnd between 1 and 20000000),
  waived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (plan_id, student_id, period),
  check (extract(day from period) = 1)
);
create index if not exists thpt_fee_charges_student_period_idx
  on public.thpt_fee_charges (student_id, period);

create table if not exists public.thpt_fee_payments (
  id bigint generated by default as identity primary key,
  charge_id bigint not null references public.thpt_fee_charges (id) on delete cascade,
  amount_vnd integer not null check (amount_vnd between 1 and 20000000),
  method text not null check (method in ('center', 'transfer')),
  paid_on date not null,
  note text not null default '' check (char_length(note) <= 300),
  recorded_by uuid references public.profiles (id),
  created_at timestamptz not null default now()
);
create index if not exists thpt_fee_payments_charge_idx on public.thpt_fee_payments (charge_id);

